import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

// The installer's build configuration names files and a version by hand; nothing else checks them (SP-H-11, SP-H-02).
// electron-builder.yml is flat, so the lines this reads need no YAML parser.

const desktop = join(import.meta.dirname, "..");
const configuration = readFileSync(join(desktop, "electron-builder.yml"), "utf8").split("\n");

const settingOf = (key: string) =>
  configuration
    .find((line) => line.startsWith(`${key}:`))
    ?.slice(key.length + 1)
    .trim();

describe("the installer's build configuration", () => {
  it("builds against the Electron the package installs", () => {
    const installed = JSON.parse(readFileSync(join(desktop, "package.json"), "utf8")).devDependencies.electron;
    expect(settingOf("electronVersion")).toBe(installed);
  });

  it("ships the license and the notices for the bundled Noise code", () => {
    const config = configuration.join("\n");
    expect(config).toContain("from: ../../LICENSE");
    expect(config).toContain("from: ../../packages/channel/NOTICE");
    const sources = [...config.matchAll(/^\s+- from: (.+)$/gm)].map((match) => match[1] ?? "");
    for (const source of sources) expect(existsSync(join(desktop, source)), source).toBe(true);
    const webNotices = readFileSync(join(desktop, "../app/public/third-party-notices.txt"), "utf8");
    expect(webNotices).toContain(readFileSync(join(desktop, "../../packages/channel/NOTICE"), "utf8"));
    expect(webNotices).toContain(readFileSync(join(desktop, "assets/one.LICENSE"), "utf8"));
  });

  it("names existing static files for the installer", () => {
    const files = configuration.join("\n").match(/^files:\n((?: {2}- .+\n)+)/m)?.[1] ?? "";
    expect(files).not.toBe("");
    for (const line of files.trim().split("\n")) {
      const file = line.trim().slice(2);
      // dist is generated by the package script before electron-builder runs.
      if (file === "dist/**") continue;
      expect(existsSync(join(desktop, file)), file).toBe(true);
    }
  });
});
