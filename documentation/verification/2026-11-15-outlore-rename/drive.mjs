import { writeFileSync } from "node:fs";
const [url, shotA, shotB] = process.argv.slice(2);
const ws = new WebSocket(url);
let id = 0; const pending = new Map();
ws.onmessage = (e) => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id); } };
const send = (method, params = {}) => new Promise((r) => { const n = ++id; pending.set(n, r); ws.send(JSON.stringify({ id: n, method, params })); });
await new Promise((r) => (ws.onopen = r));
const ev = async (expression) => (await send("Runtime.evaluate", { awaitPromise: true, expression, returnByValue: true })).result.result.value;
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const shot = async (p) => writeFileSync(p, Buffer.from((await send("Page.captureScreenshot", { format: "png" })).result.data, "base64"));
await ev(`document.querySelector('[aria-label="Ask Chronicler"]').click()`);
await wait(2500);
console.log(JSON.stringify(await ev(`({ panel: [...document.querySelectorAll('[aria-label]')].map((e) => e.getAttribute('aria-label')).filter((l) => /Chronicler|Outlore|Iskios/.test(l)), text: (document.body.innerText.match(/.{0,40}(Chronicler|Iskios|Outlore).{0,60}/g) ?? []).slice(0, 12) })`)));
await shot(shotA);
await ev(`[...document.querySelectorAll('[role="button"],button,div')].find((e) => e.innerText?.trim() === "Workshop" && e.children.length < 3)?.click()`);
await wait(1500);
await ev(`[...document.querySelectorAll('[role="button"],button,div')].find((e) => e.innerText?.trim() === "Look and feel" && e.children.length < 3)?.click()`);
await wait(1500);
console.log(JSON.stringify(await ev(`[...document.querySelectorAll('[role="radiogroup"]')].map((g) => g.getAttribute('aria-label') + ": " + [...g.querySelectorAll('[role="radio"]')].map((r) => r.innerText.trim() + (r.getAttribute('aria-checked') === 'true' ? '*' : '')).join(", "))`)));
await shot(shotB);
ws.close();
